import React, { useState } from 'react';
import { Cpu } from 'lucide-react';
import { Product } from '../types';

export function formatINR(amount: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    maximumFractionDigits: 0,
  }).format(amount);
}

export const ProductImage: React.FC<{
  src?: string;
  alt: string;
  className?: string;
  aspectClass?: string;
}> = ({ src, alt, className = '', aspectClass = 'aspect-[4/3]' }) => {
  const [failed, setFailed] = useState(false);

  if (!src || failed) {
    return (
      <div
        className={`${aspectClass} w-full bg-slate-100 border border-slate-200/80 flex flex-col items-center justify-center p-4 text-center ${className}`}
      >
        <Cpu className="w-8 h-8 text-slate-400 mb-2" strokeWidth={1.5} />
        <span className="text-xs font-medium text-slate-500 line-clamp-2 max-w-[180px]">{alt}</span>
      </div>
    );
  }

  return (
    <div className={`${aspectClass} w-full overflow-hidden bg-slate-100 ${className}`}>
      <img
        src={src}
        alt={alt}
        referrerPolicy="no-referrer"
        onError={() => setFailed(true)}
        className="w-full h-full object-cover transition-transform duration-200 ease-out group-hover:scale-[1.03]"
      />
    </div>
  );
};

export function downloadProductDatasheet(product: Product): void {
  const specsLines = Object.entries(product.specifications)
    .map(([k, v]) => `  - ${k}: ${v}`)
    .join('\n');

  const kitLines =
    product.includedComponents && product.includedComponents.length > 0
      ? `\nINCLUDED KIT BILL OF MATERIALS:\n` +
        product.includedComponents.map((c) => `  - ${c.qty}x ${c.name} (${c.spec})`).join('\n')
      : '';

  const refurbLines =
    product.division === 'refurbished'
      ? `\nREFURBISHMENT LAB RECORD:\n` +
        `  - Unit ID: ${product.unitId || 'N/A'}\n` +
        `  - Condition Grade: Grade ${product.grade || 'A'}\n` +
        `  - Testing Status: ${product.testingStatus || 'Passed All Tests'}\n` +
        `  - Physical Condition: ${product.physicalCondition || 'Inspected'}\n` +
        `  - Functional Summary: ${product.functionalTestSummary || 'Verified'}\n` +
        `  - Known Limitations: ${product.knownLimitations || 'None'}\n`
      : '';

  const content = [
    `KRONTON ENGINEERING DATASHEET & COMPLIANCE BRIEF`,
    `================================================`,
    `Product Name : ${product.name}`,
    `SKU          : ${product.sku}`,
    `Brand / Mfg  : ${product.brand} (${product.manufacturer})`,
    `Model Number : ${product.modelNumber}`,
    `Division     : ${product.division.toUpperCase()}`,
    `HSN / GST    : HSN ${product.hsnCode} (${product.gstRate}% GST)`,
    `Warranty     : ${product.warranty}`,
    ``,
    `SUMMARY:`,
    product.shortDescription,
    ``,
    `TECHNICAL SPECIFICATIONS:`,
    specsLines || '  - Standard industrial specification',
    kitLines,
    refurbLines,
    ``,
    `Datasheet Reference: ${product.datasheetSummary}`,
    `Generated by KRONTON India Storefront (https://kronton.in)`,
  ].join('\n');

  const blob = new Blob([content], { type: 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = `${product.sku}-datasheet.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
